
#include "campaign_repository.h"

#include <sqlite3.h>
#include <memory>
#include <stdexcept>
#include <string>
#include <utility>
#include <vector>

// Constructor: initialise the repository with the database path
CampaignRepository::CampaignRepository(const std::string& dbPath)
    : dbPath(dbPath) {
}


std::vector<Campaign> CampaignRepository::getAllCampaigns() {
    // Open the database in read-only mode
    sqlite3* rawDb = nullptr;
    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READONLY, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query to retrieve all campaigns
    const char* sql =
        "SELECT id, name, description FROM campaigns ORDER BY id;";

    // Prepare the SQL statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare SELECT");
    }

    // Finalise the statement automatically before closing the database
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Helper function to convert SQLite text columns to C++ strings
    auto getText = [&](int column) -> std::string {
        const unsigned char* text =
            sqlite3_column_text(stmt.get(), column);
        return text ? reinterpret_cast<const char*>(text) : "";
    };

    // Collection to store the retrieved campaigns
    std::vector<Campaign> campaigns;

    // Read each row returned by SQLite
    int result;
    while ((result = sqlite3_step(stmt.get())) == SQLITE_ROW) {
        Campaign campaign{};
        // Convert the current database row into an campaign object
        campaign.id = sqlite3_column_int(stmt.get(), 0);
        campaign.name = getText(1);
        campaign.description = getText(2);
        // Move the completed campaign object into the vector to avoid copying
        campaigns.push_back(std::move(campaign));
    }

    // Check that the query completed without errors
    if (result != SQLITE_DONE) {
        throw std::runtime_error("Failed to retrieve campaigns");
    }

    return campaigns;
}


Campaign CampaignRepository::createCampaign(const Campaign& campaign) {
    // Open the SQLite database for reading and writing
    sqlite3* rawDb = nullptr;
    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READWRITE, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query using placeholders to prevent SQL injection
    const char* sql =
        "INSERT INTO campaigns (name, description) "
        "VALUES (?, ?);";

    // Prepare the INSERT statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare INSERT");
    }

    // Automatically release the statement before closing the database
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Bind campaign fields to the SQL placeholders
    int bindResult = SQLITE_OK;
    bindResult = sqlite3_bind_text(stmt.get(), 1, campaign.name.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 2, campaign.description.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult != SQLITE_OK) {
        throw std::runtime_error("Failed to bind Campaign values");
    }

    // Execute the INSERT statement
    if (sqlite3_step(stmt.get()) != SQLITE_DONE) {
        throw std::runtime_error("Failed to insert Campaign");
    }

    // Create a copy with the ID generated by SQLite
    Campaign createdCampaign = campaign;
    createdCampaign.id = static_cast<int>(sqlite3_last_insert_rowid(db.get()));

    return createdCampaign;
}


bool CampaignRepository::updateCampaign(const Campaign& campaign) {
    // Open SQLite database for reading and writing
    sqlite3* rawDb = nullptr;
    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READWRITE, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query to update the campaign matching the given ID
    const char* sql =
        "UPDATE campaigns "
        "SET name = ?, description = ? "
        "WHERE id = ?;";

    // Prepare the UPDATE statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare UPDATE");
    }

    // Automatically release the prepared statement
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Bind campaign fields to the SQL placeholders
    int bindResult = SQLITE_OK;
    bindResult = sqlite3_bind_text(stmt.get(), 1, campaign.name.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 2, campaign.description.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_int(stmt.get(), 3, campaign.id);
    if (bindResult != SQLITE_OK) {
        throw std::runtime_error("Failed to bind campaign values");
    }

    // Execute the UPDATE statement
    if (sqlite3_step(stmt.get()) != SQLITE_DONE) {
        throw std::runtime_error("Failed to update campaign");
    }

    // Return true if a campaign with this ID was matched
    return sqlite3_changes(db.get()) > 0;
}


bool CampaignRepository::deleteCampaign(int id) {
    // Open SQLite database for reading and writing
    sqlite3* rawDb = nullptr;
    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READWRITE, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query to delete the campaign matching the given ID
    const char* sql = "DELETE FROM campaigns WHERE id = ?;";

    // Prepare the DELETE statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare DELETE");
    }

    // Automatically release the prepared statement
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Bind the campaign ID to the SQL placeholder
    if (sqlite3_bind_int(stmt.get(), 1, id) != SQLITE_OK) {
        throw std::runtime_error("Failed to bind campaign ID");
    }

    // Execute the DELETE statement
    if (sqlite3_step(stmt.get()) != SQLITE_DONE) {
        throw std::runtime_error("Failed to delete campaign");
    }

    // Return true if an campaign was deleted
    return sqlite3_changes(db.get()) > 0;
}
