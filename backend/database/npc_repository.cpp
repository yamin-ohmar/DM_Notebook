
#include "npc_repository.h"

#include <sqlite3.h>
#include <stdexcept>
#include <string>
#include <vector>
#include <memory>
#include <utility>


// Constructor
NPCRepository::NPCRepository(const std::string& dbPath)
    : dbPath(dbPath) {
}


std::vector<NPC> NPCRepository::getAllNPCs() {
    // Open the SQLite database in read-only mode
    sqlite3* rawDb = nullptr;

    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READONLY, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends (using smart pointer)
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query to retrieve all NPCs
    const char* sql =
        "SELECT id, name, race, role, description FROM npcs ORDER BY id;";

    // Prepare the SQL statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare SELECT");
    }

    // Automatically release the prepared statement (using smart pointer)
    // RAII cleanup: stmt is destroyed before db (reverse creation order)
    // This finalizes the statement before closing the database
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Helper function to convert SQLite text into a C++ string
    auto getText = [&](int column) -> std::string {
        const unsigned char* text = sqlite3_column_text(stmt.get(), column);
        return text ? reinterpret_cast<const char*>(text) : "";
    };

    // Collection to store the retrieved NPCs
    std::vector<NPC> npcs;

    // Read each row returned by SQLite
    int result;
    while ((result = sqlite3_step(stmt.get())) == SQLITE_ROW) {
        NPC npc;
        // Convert the current database row into an NPC object
        npc.id = sqlite3_column_int(stmt.get(), 0);
        npc.name = getText(1);
        npc.race = getText(2);
        npc.role = getText(3);
        npc.description = getText(4);

        // Move the completed NPC object into the vector to avoid copying
        npcs.push_back(std::move(npc));
    }

    // Check that the query completed without errors
    if (result != SQLITE_DONE) {
        throw std::runtime_error("Failed to read NPC records");
    }

    // Return all retrieved NPCs
    return npcs;
}


NPC NPCRepository::createNPC(const NPC& npc) {
    // Open the SQLite database for reading and writing
    sqlite3* rawDb = nullptr;
    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READWRITE, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query using placeholders to prevent SQL injection
    const char* sql =
        "INSERT INTO npcs (name, race, role, description) "
        "VALUES (?, ?, ?, ?);";

    // Prepare the INSERT statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare INSERT");
    }

    // Automatically release the statement before closing the database
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Bind NPC fields to the SQL placeholders
    int bindResult = SQLITE_OK;
    bindResult = sqlite3_bind_text(stmt.get(), 1, npc.name.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 2, npc.race.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 3, npc.role.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 4, npc.description.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult != SQLITE_OK) {
        throw std::runtime_error("Failed to bind NPC values");
    }

    // Execute the INSERT statement
    if (sqlite3_step(stmt.get()) != SQLITE_DONE) {
        throw std::runtime_error("Failed to insert NPC");
    }

    // Create a copy with the ID generated by SQLite
    NPC createdNPC = npc;
    createdNPC.id = static_cast<int>(sqlite3_last_insert_rowid(db.get()));

    return createdNPC;
}


bool NPCRepository::updateNPC(const NPC& npc) {
    // Open SQLite database for reading and writing
    sqlite3* rawDb = nullptr;
    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READWRITE, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query to update the NPC matching the given ID
    const char* sql =
        "UPDATE npcs "
        "SET name = ?, race = ?, role = ?, description = ? "
        "WHERE id = ?;";

    // Prepare the UPDATE statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare UPDATE");
    }

    // Automatically release the prepared statement
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Bind NPC fields to the SQL placeholders
    int bindResult = SQLITE_OK;
    bindResult = sqlite3_bind_text(stmt.get(), 1, npc.name.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 2, npc.race.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 3, npc.role.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_text(stmt.get(), 4, npc.description.c_str(), -1, SQLITE_TRANSIENT);
    if (bindResult == SQLITE_OK)
        bindResult = sqlite3_bind_int(stmt.get(), 5, npc.id);
    if (bindResult != SQLITE_OK) {
        throw std::runtime_error("Failed to bind NPC values");
    }

    // Execute the UPDATE statement
    if (sqlite3_step(stmt.get()) != SQLITE_DONE) {
        throw std::runtime_error("Failed to update NPC");
    }

    // Return true if an NPC with this ID was matched
    return sqlite3_changes(db.get()) > 0;
}


bool NPCRepository::deleteNPC(int id) {
    // Open SQLite database for reading and writing
    sqlite3* rawDb = nullptr;
    if (sqlite3_open_v2(dbPath.c_str(), &rawDb,
                        SQLITE_OPEN_READWRITE, nullptr) != SQLITE_OK) {
        sqlite3_close(rawDb);
        throw std::runtime_error("Failed to open database");
    }

    // Automatically close the database when the function ends
    std::unique_ptr<sqlite3, decltype(&sqlite3_close)>
        db(rawDb, sqlite3_close);

    // SQL query to delete the NPC matching the given ID
    const char* sql = "DELETE FROM npcs WHERE id = ?;";

    // Prepare the DELETE statement
    sqlite3_stmt* rawStmt = nullptr;
    if (sqlite3_prepare_v2(db.get(), sql, -1, &rawStmt, nullptr) != SQLITE_OK) {
        throw std::runtime_error("Failed to prepare DELETE");
    }

    // Automatically release the prepared statement
    std::unique_ptr<sqlite3_stmt, decltype(&sqlite3_finalize)>
        stmt(rawStmt, sqlite3_finalize);

    // Bind the NPC ID to the SQL placeholder
    if (sqlite3_bind_int(stmt.get(), 1, id) != SQLITE_OK) {
        throw std::runtime_error("Failed to bind NPC ID");
    }

    // Execute the DELETE statement
    if (sqlite3_step(stmt.get()) != SQLITE_DONE) {
        throw std::runtime_error("Failed to delete NPC");
    }

    // Return true if an NPC was deleted
    return sqlite3_changes(db.get()) > 0;
}
